const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

const manifest = read('android/warehouse/app/src/main/AndroidManifest.xml')
const build = read('android/warehouse/app/build.gradle')
const launcher = read('android/warehouse/app/src/main/java/com/dataplus/warehouse/LauncherActivity.java')
const api = read('android/warehouse/app/src/main/java/com/dataplus/warehouse/ApiClient.java')
const webFallback = read('android/warehouse/app/src/main/java/com/dataplus/warehouse/WebFallbackActivity.java')
const server = read('server.js')

assert.match(build, /applicationId 'com\.dataplus\.warehouse'/)
assert.match(build, /versionCode 4/)
assert.match(build, /versionName '2\.2\.0'/)
assert.doesNotMatch(build, /android-browser-helper|trusted-web-activity/i)

assert.match(manifest, /android:name="\.LauncherActivity"/)
assert.match(manifest, /android:name="\.WebFallbackActivity"/)
assert.match(manifest, /android:usesCleartextTraffic="false"/)
assert.doesNotMatch(manifest, /TrustedWebActivity|browserhelper|DelegationService/)

assert.match(launcher, /public boolean dispatchKeyEvent\(KeyEvent event\)/)
assert.match(launcher, /KEYCODE_ENTER/)
assert.match(launcher, /KEYCODE_NUMPAD_ENTER/)
assert.match(launcher, /KEYCODE_TAB/)
assert.ok(launcher.indexOf('/lookup"') < launcher.indexOf('/scan"'), 'native flow must look up before saving')
assert.match(launcher, /Confirm scanned item/)
assert.match(launcher, /Unit of measure/)
assert.match(launcher, /Case pack/)
assert.match(launcher, /Quantity to receive/)
assert.match(launcher, /Offline — reconnect before scanning/)
assert.match(launcher, /Nothing was received\. Skip it or use the full DataPlus workflow/)
assert.match(launcher, /SCREEN_OUTBOUND/)
assert.match(launcher, /Outbound handoffs/)
assert.match(launcher, /Tracking scanner ready/)
assert.match(launcher, /Scan package items/)
assert.match(launcher, /\/api\/fulfillment\/outbound-audits\?limit=100/)
assert.match(launcher, /\/item-scan/)
assert.match(launcher, /\/reconcile/)
assert.match(launcher, /\/close/)
assert.match(launcher, /Photos & exceptions/)
assert.match(launcher, /Scan to open a handoff/)
assert.match(launcher, /Matched " \+ currentOutboundSession\.optInt\("matchedCount"\)/)
assert.match(launcher, /Unmatched " \+ currentOutboundSession\.optInt\("unmatchedCount"\)/)
assert.match(launcher, /Tap to view package details/)
assert.match(launcher, /item verification: " \+ scanned \+ " of " \+ expected \+ " scanned"/)

assert.match(api, /https:\/\/dataplusapp\.duckdns\.org/)
assert.match(api, /CookieManager\.getInstance\(\)/)
assert.match(api, /setRequestProperty\("Cookie", cookies\)/)
assert.match(api, /setCookie\(BASE_URL, cookie\)/)
assert.match(launcher, /\/api\/auth\/session/)
assert.match(launcher, /\/api\/auth\/login/)

assert.match(webFallback, /TRUSTED_ORIGIN/)
assert.match(webFallback, /MIXED_CONTENT_NEVER_ALLOW/)
assert.match(webFallback, /setUserAgentString[\s\S]*DataPlusWarehouse\/2\.2\.0/)
assert.match(webFallback, /setAllowFileAccess\(false\)/)
assert.match(webFallback, /setAllowContentAccess\(false\)/)
assert.match(webFallback, /PermissionRequest\.RESOURCE_VIDEO_CAPTURE/)
assert.match(webFallback, /openExternal\(uri\)/)

const scanner = read('web/src/lib/fast-barcode-scanner.ts')
const outboundWorkspace = read('web/src/components/outbound-audit-workspace.tsx')
assert.match(scanner, /scanner\|barcode\|imager\|infrared\|monochrome/)
assert.match(scanner, /selectRegularRearCameraDeviceId[\s\S]*width: \{ ideal: 3840 \}[\s\S]*height: \{ ideal: 2160 \}/)
assert.match(outboundWorkspace, /preferRegularRearCamera: isNativeWarehouseWebView\(\)/)

assert.match(server, /parts\[3\] === "lookup"/)
assert.match(server, /parts\[3\] === "scan"/)
assert.match(server, /url\.pathname === "\/api\/auth\/session"/)
assert.match(server, /url\.pathname === "\/api\/app\/references"/)

console.log('Native Warehouse Android package, inbound and outbound G47 capture, confirmation, session sharing, offline guard, and restricted web fallback checks passed.')
