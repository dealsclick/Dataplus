const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('../web/node_modules/typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../web/src/App.tsx'), 'utf8');
const start = source.indexOf('type WarehouseAuditSort =');
const end = source.indexOf('function WarehouseAuditSortControl', start);
const context = vm.createContext({});
vm.runInContext(ts.transpile(source.slice(start, end), { target: ts.ScriptTarget.ES2020 }), context);
const sort = (rows, order, items) => Array.from(context.sortWarehouseAuditRows(rows, order, items), row => row.id);
const rows = [{id:'old',sku:'SKU-2',firstScannedAt:'2026-09-17T12:00:00Z',lastScannedAt:'2026-09-20T12:00:00Z'}, {id:'unknown',barcode:'UPC-1',scannedAt:'2026-09-18T12:00:00Z'}, {id:'new',sku:'SKU-10',firstScannedAt:'2026-09-19T12:00:00Z'}];
assert.deepEqual(sort(rows,'newest',true),['new','unknown','old']);
assert.deepEqual(sort(rows,'oldest',true),['old','unknown','new']);
assert.deepEqual(sort(rows,'identifier',true),['old','new','unknown']);
assert.deepEqual(rows.map(row=>row.id),['old','unknown','new']);
assert.deepEqual(sort([{id:'a'},{id:'b'}],'newest',true),['b','a']);
assert.deepEqual(sort([{id:'a'},{id:'b'}],'newest',false),['a','b']);
assert.deepEqual(sort([{id:'old',createdAt:'2026-09-17'},{id:'new',createdAt:'2026-09-18'}],'newest',false),['new','old']);
console.log('Audit sorting: known/unknown chronology, user sort choices, stable ties, no source mutation.');
