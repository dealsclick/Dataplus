const assert = require('node:assert/strict');
const { withDataWarehouseStock, dataWarehouseStockRow } = require('../lib/inventory-locations');
const { inventoryAmount } = require('../lib/walmart-operations');
const stamp = '2026-09-10T15:01:16.700Z';
const legacy = { sku: 'BUS01SSC9789DH', supplier: 'D&H', stockQty: 6, qty: 6, productDumpUpdatedAt: stamp, warehouseStock: [] };
const result = withDataWarehouseStock(legacy);
assert.equal(result.warehouseStock[0].qty, 6);
assert.equal(result.warehouseStock[0].isPhysical, false);
assert.equal(result.warehouseStock[0].updatedAt, stamp);
assert.equal(legacy.warehouseStock.length, 0, 'read projection does not mutate source');
assert.equal(withDataWarehouseStock({...legacy, warehouseStock:[dataWarehouseStockRow(0,stamp)]}).warehouseStock[0].qty,0,'explicit zero wins');
assert.equal(withDataWarehouseStock({qty:6,warehouseStock:[]}).warehouseStock.length,0,'aggregate qty is not supplier evidence');
assert.equal(withDataWarehouseStock({...legacy,stockQty:null}).warehouseStock.length,0);
assert.equal(withDataWarehouseStock({...legacy,productDumpUpdatedAt:'invalid'}).warehouseStock.length,0);
const both=withDataWarehouseStock({...legacy,warehouseStock:[{warehouseId:'physical',qty:4,reserved:1,isPhysical:true}]});
assert.equal(both.warehouseStock.length,2);
const db={warehouses:[{id:'datawarehouse',inventorySourceType:'supplier_feed',isPhysical:false},{id:'physical',isPhysical:true}],vendors:[]};
const rules={walmartWarehouseId:'datawarehouse',walmartSafetyQty:2};
assert.equal(inventoryAmount(both,db,rules,1),4,'supplier quantity minus threshold');
assert.equal(inventoryAmount({...both,stockQty:100},db,rules,1),4,'do not double-count source fallback');
assert.equal(inventoryAmount(both,db,{...rules,walmartSafetyQty:6},1),0,'at threshold sends zero');
assert.equal(inventoryAmount(both,db,{...rules,walmartWarehouseId:'physical'},1),1,'physical stock independent');
assert.equal(inventoryAmount(both,db,{...rules,walmartMaxQuantity:3},1),3);
assert.equal(inventoryAmount(both,db,rules,2),1,'pack units before reserve');
assert.equal(inventoryAmount({...both,active:false},db,rules,1),0);
assert.equal(inventoryAmount(both,{...db,vendors:[{name:'D&H',active:false}]},rules,1),0);
assert.equal(inventoryAmount(both,{...db,vendors:[{name:'D&H',inventoryRules:{safetyQty:5}}]},rules,1),1);
console.log('PASS supplier/physical stock separation, zero precedence, source timestamps, threshold, packs and selling gates');
