const assert = require("node:assert/strict");
const { classifyShipping, normalizeShippingRules } = require("../lib/shipping-classification");
const box = (l, w, h, weight = 10) => ({ packageLength: l, packageWidth: w, packageHeight: h, packageWeight: weight });
assert.equal(classifyShipping(box(24.5, 16.3, 18.5)).shippingClass, "parcel");
assert.equal(classifyShipping(box(24.5, 16.3, 18.5)).dimensionalWeight, 53.151);
assert.equal(classifyShipping(box(60, 1.13, 1.13)).shippingClass, "parcel");
assert.equal(classifyShipping(box(120, 2, 2)).shippingClass, "ltl");
assert.equal(classifyShipping(box(20, 20, 20, 53)).shippingClass, "parcel");
assert.equal(classifyShipping(box(20, 20, 20, 150)).shippingClass, "parcel");
assert.equal(classifyShipping(box(20, 20, 20, 150.01)).shippingClass, "ltl");
assert.equal(classifyShipping(box(108, 2, 2)).shippingClass, "parcel");
assert.equal(classifyShipping(box(108.01, 2, 2)).shippingClass, "ltl");
assert.equal(classifyShipping(box(61, 26, 26)).shippingClass, "parcel");
assert.equal(classifyShipping(box(61.1, 26, 26)).shippingClass, "ltl");
assert.equal(classifyShipping(box(60, 1, 1), { shippingLongParcelLength: 65 }).shippingClass, "parcel");
assert.equal(classifyShipping({ shipMode: "LTL" }).shippingClass, "ltl");
assert.equal(classifyShipping({ shipMode: "LTL" }, { shippingHonorSupplierFreight: false }).shippingClass, "missing_measurements");
assert.equal(classifyShipping({ ...box(10, 10, 10), shippingMethod: "LTL", shippingClass: "ltl", dimensionalWeight: 900 }).shippingClass, "parcel");
assert.equal(classifyShipping({ packageLength: 120 }).shippingClass, "ltl");
assert.equal(classifyShipping({ packageLength: 20, itemWidth: 5, itemHeight: 5 }).shippingClass, "missing_measurements");
assert.equal(classifyShipping({ ...box(10, 10, 10), shippingClassOverride: "ltl", shippingOverrideReason: "Supplier pallet only" }).shippingClass, "ltl");
assert.equal(classifyShipping({ ...box(120, 2, 2), shippingClassOverride: "parcel", shippingOverrideReason: "Ships disassembled" }).shippingClass, "ltl");
assert.equal(classifyShipping(box(10, 10, 10), { shippingDimensionalDivisor: 100 }).dimensionalWeight, 10);
assert.equal(normalizeShippingRules({ shippingParcelMaxWeight: -1 }).shippingParcelMaxWeight, 150);
console.log("Shipping classification checks passed.");
const fs = require("node:fs");
const vm = require("node:vm");
const source = fs.readFileSync(require.resolve("../server"), "utf8");
const gateCode = source.slice(source.indexOf("function channelShippingRestriction("), source.indexOf("function normalizedCompareValue("));
const context = { productShippingClassification: classifyShipping };
vm.createContext(context);
vm.runInContext(gateCode, context);
const gate = context.channelShippingRestriction;
assert.equal(gate(box(24.5, 16.3, 18.5), {}, "inventory").blocked, false);
assert.equal(gate(box(60, 1, 1), {}, "launch").blocked, false);
assert.equal(gate(box(60, 1, 1), { shippingRestrictOversizeLaunch: false }, "launch").blocked, false);
assert.equal(gate({ shipMode: "LTL" }, {}, "inventory").blocked, true);
assert.equal(gate({}, { shippingRestrictMissingMeasurementsLaunch: true }, "launch").blocked, true);
assert.equal(gate(box(120, 2, 2), { shippingRestrictionGateEnabled: false }, "launch").blocked, false);
console.log("Channel shipping gate checks passed.");
assert.equal(classifyShipping({ ...box(60, 1, 1), shippingClassOverride: "oversize_parcel" }).shippingClass, "parcel");
assert.equal(classifyShipping({ ...box(120, 1, 1), shippingClassOverride: "oversize_parcel" }).shippingClass, "ltl");
assert.equal(gate(box(60, 1, 1), { shippingRestrictOversizeLaunch: true }, "launch").blocked, false);
assert.equal(gate(box(60, 1, 1), { shippingRestrictOversizeInventory: true }, "inventory").blocked, false);
assert.equal(classifyShipping({ packageLength: 60 }).shippingClass, "missing_measurements");
assert.equal(normalizeShippingRules({ shippingParcelMaxLength: 200 }).shippingParcelMaxLength, 108);
assert.equal(normalizeShippingRules({ shippingParcelMaxGirth: 200 }).shippingParcelMaxGirth, 165);
assert.equal(normalizeShippingRules({ shippingParcelMaxWeight: 200 }).shippingParcelMaxWeight, 150);
console.log("FedEx Ground compatibility and carrier ceiling checks passed.");
