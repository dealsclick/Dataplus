const assert = require('node:assert/strict');
const { resolvePricePolicy, applyPricePolicy, validatePriceMode } = require('../lib/channel-price-policy');
const shop = { id: 'shop-1', name: 'Shopify', settings: { mapPricingMode: 'protected' } };
const ebay = { id: 'ebay-1', name: 'eBay', settings: { mapPricingMode: 'protected' } };
const db = { brands: [{ name: 'Acme', mapPricingMode: 'calculated' }] };
const item = { brand: ' ACME ', mapPrice: 400, lapPrice: 450 };
assert.deepEqual(resolvePricePolicy(item, db, shop), { mode: 'calculated', source: 'brand' });
assert.equal(applyPricePolicy(378, item, db, shop), 378);
const override = { ...item, channelPriceModes: { 'shop-1': 'protected' } };
assert.equal(applyPricePolicy(378, override, db, shop), 450);
assert.equal(applyPricePolicy(378, override, db, ebay), 378);
assert.equal(applyPricePolicy(500, override, db, shop), 500);
assert.equal(applyPricePolicy(378, { ...override, channelPriceModes: { 'shop-1': 'inherit' } }, db, shop), 378);
assert.equal(applyPricePolicy(378, item, {}, shop), 450);
assert.equal(applyPricePolicy(378, item, {}, { ...shop, settings: { mapPricingMode: 'calculated' } }), 378);
assert.equal(applyPricePolicy(378, item, {}, {}), 450);
assert.equal(applyPricePolicy(600, override, db, shop, 2), 900);
assert.equal(applyPricePolicy(300, override, db, shop, 2, 2), 450);
assert.equal(applyPricePolicy(0, override, db, shop), 0);
assert.equal(applyPricePolicy(NaN, override, db, shop), 0);
assert.throws(() => validatePriceMode('ignore'));
assert.throws(() => validatePriceMode('inherit', false));
assert.equal(validatePriceMode('inherit'), 'inherit');
assert.equal(applyPricePolicy(128, { minimumAllowedPrice: 0, original: { minimum_allowed_price: 160 } }, {}, shop), 160);
console.log('Channel/brand/SKU precedence, channel isolation, floors, UOM and validation passed.');
